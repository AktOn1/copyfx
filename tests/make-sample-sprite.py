#!/usr/bin/env python3
"""Builds the fake selection used by gallery cards and posters of the "by image" effects: renders a highlighted line of text,
runs find-selection on it (sprites=) and writes posters/sample-sprite.png + sample-sprite.js (+ .json for the test scripts)."""
import json, os, subprocess, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "posters")
os.makedirs(OUT, exist_ok=True)
tmp = os.path.join(OUT, ".tmp")
os.makedirs(tmp, exist_ok=True)
f = ImageFont.truetype("/usr/share/fonts/liberation/LiberationSans-Regular.ttf", 15)
im = Image.new("RGB", (264, 130), (32, 35, 42))
d = ImageDraw.Draw(im)
text = "Copied to clipboard"
w = int(d.textlength(text, font=f))
x0, y0 = 32, 56
d.rectangle((x0, y0, x0 + w + 1, y0 + 19), fill=(52, 101, 164))
d.text((x0 + 1, y0 + 1), text, font=f, fill=(255, 255, 255))
shot = os.path.join(tmp, "shot.png")
im.save(shot)
out = subprocess.run([sys.executable, os.path.join(ROOT, "find-selection"), "--image", shot, str(x0 + w), str(y0 + 9), "sprites=" + tmp, "accent=#f19d88"],
                     capture_output=True, text=True).stdout
res = json.loads(out)
assert res["found"] and res.get("sprite"), res
sp = res["sprite"]
os.replace(sp["file"], os.path.join(OUT, "sample-sprite.png"))
for n in os.listdir(tmp):
    os.remove(os.path.join(tmp, n))
os.rmdir(tmp)
rects = res["rects"]
sprite = {"x": sp["x"], "y": sp["y"], "w": sp["w"], "h": sp["h"], "rows": sp["rows"]}
json.dump({"rects": rects, "sprite": dict(sprite, url="file://" + os.path.join(OUT, "sample-sprite.png")), "text": text}, open(os.path.join(OUT, "sample-sprite.json"), "w"))
open(os.path.join(ROOT, "sample-sprite.js"), "w").write(
    ".pragma library\n\n// GENERATED by tests/make-sample-sprite.py: the fake selection shown on gallery cards of the by-image effects.\n"
    "var text = %s\nvar rects = %s\nvar sprite = { url: Qt.resolvedUrl(\"posters/sample-sprite.png\"), x: %d, y: %d, w: %d, h: %d, rows: %d }\n"
    % (json.dumps(text), json.dumps(rects), sp["x"], sp["y"], sp["w"], sp["h"], sp["rows"]))
print("sample sprite:", sprite, len(rects), "rect(s)")
